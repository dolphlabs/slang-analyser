#!/usr/bin/env python3
"""Generate crates/slang_hir/src/native_sigs_generated.rs from a slang checkout.

Reads every src/codegen/pkg_*/sigs.c NatSig table plus the json special
forms in pkg_json/dispatch.c, and emits a static Rust signature table used
for hover text and return-type inference of native calls.

Usage:
    python3 scripts/gen_native_sigs.py /path/to/slang [slang-commit]

The slang commit defaults to the checkout's HEAD. The generated file
records it; re-run on slang updates and commit the result.
"""
import re
import subprocess
import sys
from pathlib import Path

ARGKIND = {
    "NA_INT": "int",
    "NA_I64": "int",
    "NA_F64": "float",
    "NA_STR": "str",
    "NA_STR_FAULT": "str",
    "NA_BYTES": "bytes",
    "NA_RAWPTR": "rawptr",
    "NA_ARR_STR": "[str]",
    "NA_ARR_BYTES": "[bytes]",
    "NA_WIRE": "wire",
    "NA_UNTIL": "until",
}

ROW = re.compile(
    r'\{"([a-z_0-9]+)", "([a-z_0-9]+)", (\d+), \{([^}]*)\}, (NULL|"[^"]*"), [01]\},?'
)


def parse_sigs(path):
    rows = []
    for line in path.read_text().splitlines():
        m = ROW.search(line)
        if not m:
            continue
        pkg, name, nargs, kinds, ret = m.groups()
        kinds = [k.strip() for k in kinds.split(",") if k.strip() and k.strip() != "0"]
        params = []
        for k in kinds:
            if k not in ARGKIND:
                raise SystemExit(f"unknown arg kind {k} in {path}:{line.strip()}")
            params.append(ARGKIND[k])
        assert len(params) == int(nargs), f"nargs mismatch: {line.strip()}"
        rows.append((pkg, name, params, None if ret == "NULL" else ret[1:-1]))
    return rows


def main():
    slang = Path(sys.argv[1])
    codegen = slang / "src" / "codegen"
    if not (codegen / "native.c").exists():
        raise SystemExit(f"not a slang checkout: {slang}")
    commit = (
        sys.argv[2]
        if len(sys.argv) > 2
        else subprocess.run(
            ["git", "-C", str(slang), "rev-parse", "--short", "HEAD"],
            capture_output=True,
            text=True,
        ).stdout.strip()
    )
    rows = []
    for sigs in sorted(codegen.glob("pkg_*/sigs.c")):
        rows.extend(parse_sigs(sigs))
    # json is generic over the target type (see json_call_infer in
    # pkg_json/dispatch.c): encode takes anything and returns str;
    # decode takes str|bytes and returns the expected result[T, str].
    rows.append(("json", "encode", ["value"], "str"))
    rows.append(("json", "decode", ["str"], "result[T, str]"))

    out = [
        "// Generated by scripts/gen_native_sigs.py — do not edit by hand.",
        f"// Source: slang @ {commit} (src/codegen/pkg_*/sigs.c, pkg_json/dispatch.c).",
        "// Re-run the script on slang updates and commit the result.",
        "",
        "/// One native-package function signature.",
        "/// `params` are rendered slang types (`int`, `str`, `[str]`, ...);",
        "/// `ret` is `None` for void. Mirrors NatSig + doc.c argkind_name.",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
        "pub struct NativeSig {",
        "    pub pkg: &'static str,",
        "    pub name: &'static str,",
        "    pub params: &'static [&'static str],",
        "    pub ret: Option<&'static str>,",
        "}",
        "",
        "#[rustfmt::skip]",
        "pub static NATIVE_SIGS: &[NativeSig] = &[",
    ]
    for pkg, name, params, ret in rows:
        ps = ", ".join(f'"{p}"' for p in params)
        r = f'Some("{ret}")' if ret is not None else "None"
        out.append(
            f'    NativeSig {{ pkg: "{pkg}", name: "{name}", '
            f"params: &[{ps}], ret: {r} }},"
        )
    out += [
        "];",
        "",
        "/// Look up a native-package function, like native.c find_any_sig.",
        "pub fn native_sig(pkg: &str, name: &str) -> Option<&'static NativeSig> {",
        "    NATIVE_SIGS.iter().find(|s| s.pkg == pkg && s.name == name)",
        "}",
        "",
    ]
    dest = Path("crates/slang_hir/src/native_sigs_generated.rs")
    dest.write_text("\n".join(out))
    pkgs = sorted({p for p, _, _, _ in rows})
    print(f"wrote {dest}: {len(rows)} sigs across {len(pkgs)} packages ({', '.join(pkgs)})")


if __name__ == "__main__":
    main()
